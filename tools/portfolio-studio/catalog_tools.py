"""Portfolio media catalog: stable single source for public Photography gallery.

data/media-catalog.json is the source of truth. js/photography-catalog.js is
generated from it, because the static website loads the gallery as a script.
Every catalog writer saves the two files together.

This file is local development tooling, not executed by website visitors.
"""
import json
import math
import os
import sys
import tempfile
from pathlib import Path
from urllib.parse import quote

TAGS = ["Day", "Moody", "Dusk", "Night", "Concrete Jungle", '"It\'s just rocks"', "Sky"]
VALID_PRIORITY = {"low", "normal", "portraitBoost", "featured"}
SENTINEL = "// GENERATED FROM data/media-catalog.json. DO NOT EDIT THIS FILE DIRECTLY.\n"

def read_json(path):
    with Path(path).open("r",encoding="utf-8") as f:
        return json.load(f)

def validate_catalog(catalog,repo=None):
    """Raise ValueError if the catalog is malformed; with repo, also require each photo file.

    Returns the photo count.
    """
    if catalog.get("schemaVersion") != 1:
        raise ValueError("Expected media catalog schemaVersion 1")
    tags=catalog.get("photoTags")
    photos=catalog.get("photos")
    if not isinstance(tags,list) or len(tags)!=len(set(tags)) or not all(isinstance(t,str) and t.strip() for t in tags):
        raise ValueError("Invalid photoTags")
    if not isinstance(photos,list):
        raise ValueError("Invalid photo catalog")
    seen=set()
    for p in photos:
        if not isinstance(p,dict):
            raise ValueError("Invalid photo entry")
        filename=p.get("file")
        if not isinstance(filename,str) or not filename or '/' in filename or '\\' in filename or '..' in filename:
            raise ValueError(f"Unsafe filename: {filename!r}")
        if filename.casefold() in seen:
            raise ValueError(f"Duplicate filename: {filename}")
        seen.add(filename.casefold())
        thumbnail=p.get("thumbnail")
        if thumbnail is not None:
            if not isinstance(thumbnail,str) or not thumbnail or '/' in thumbnail or '\\' in thumbnail or '..' in thumbnail:
                raise ValueError(f"Unsafe thumbnail filename: {thumbnail!r}")
            if repo is not None and not (Path(repo)/"photography"/"thumbnails"/thumbnail).is_file():
                raise ValueError(f"Missing gallery thumbnail: {thumbnail}")
        if not isinstance(p.get("alt"),str) or not p["alt"].strip():
            raise ValueError(f"Missing alt text in {filename}")
        r=p.get("aspectRatio")
        if not isinstance(r,(float,int)) or not .05 < r < 25:
            raise ValueError(f"Bad aspect ratio in {filename}")
        crop=p.get("galleryCrop")
        if crop is not None:
            if not isinstance(crop,dict) or set(crop)!={"x","y","width","height"}:
                raise ValueError(f"Invalid crop rectangle in {filename}")
            try:
                x,y,w,h=(float(crop[k]) for k in ("x","y","width","height"))
            except (ValueError, TypeError, KeyError) as exc:
                raise ValueError(f"Non-numeric crop in {filename}") from exc
            if not all(math.isfinite(v) for v in (x,y,w,h)) or not (
                0<=x<=1 and 0<=y<=1 and .012<=w<=1 and .012<=h<=1
                and x+w<=1.000001 and y+h<=1.000001):
                raise ValueError(f"Crop out of bounds in {filename}")
        if not isinstance(p.get("tags"),list) or any(t not in tags for t in p["tags"]):
            raise ValueError(f"Unknown photo tag on {filename}")
        if "publishedImage" in p and type(p["publishedImage"]) is not bool:
            raise ValueError("Invalid Published Image marker")
        if p.get("publishedImage") is True and not thumbnail:
            raise ValueError(f"Published Image requires thumbnail: {filename}")
        if repo is not None and not p.get("publishedImage") and not (Path(repo)/"photography"/"published"/filename).is_file():
            raise ValueError(f"Missing publication image {filename}")
    return len(photos)

def generated_js(catalog):
    """The website's gallery script for a validated catalog (editor-only fields removed)."""
    validate_catalog(catalog)
    photos=[]
    ratios={}
    for p in catalog["photos"]:
        keep={k:v for k,v in p.items() if k not in ("aspectRatio","tagStatus","altNeedsReview")}
        photos.append(keep)
        crop=p.get("galleryCrop")
        # Canonical floating ratios match Electron's generated script after JSON round trips.
        ratio=float(p["aspectRatio"])
        ratios[p["file"]]=ratio * crop["width"]/crop["height"] if crop else ratio
    return (
       SENTINEL +
       "window.PORTFOLIO_PHOTOS = " + json.dumps(photos,ensure_ascii=False,indent=2) + ";\n" +
       "window.PHOTO_ASPECT_RATIOS = " + json.dumps(ratios,ensure_ascii=False,indent=2) + ";\n" +
       "window.PHOTO_TAG_LABELS = " + json.dumps(catalog["photoTags"],ensure_ascii=False) + ";\n"
    )

def sync(repo):
    """Regenerate js/photography-catalog.js from the catalog if it is out of date (repair CLI)."""
    repo=Path(repo).resolve()
    c=read_json(repo/"data"/"media-catalog.json")
    count=validate_catalog(c,repo)
    target=repo/"js"/"photography-catalog.js"
    updated=generated_js(c)
    if not target.is_file() or target.read_text(encoding="utf-8")!=updated:
        temporary=None
        try:
            with tempfile.NamedTemporaryFile(mode="w",encoding="utf-8",newline="\n",
                    dir=target.parent,prefix=".photography-catalog-",suffix=".tmp",delete=False) as staged:
                temporary=Path(staged.name)
                staged.write(updated)
                staged.flush()
                os.fsync(staged.fileno())
            # Close first: Windows cannot replace an open NamedTemporaryFile.
            os.replace(temporary,target)
        finally:
            if temporary is not None:
                temporary.unlink(missing_ok=True)
    print(f"Catalog synchronized: {count} Photography images")
    return count

if __name__ == "__main__":
    candidate=Path(__file__).resolve().parents[2]
    try:
        sync(Path(sys.argv[1]) if len(sys.argv)>1 else candidate)
    except (ValueError,OSError,KeyError) as exc:
        sys.exit(f"CATALOG ERROR: {exc}")
