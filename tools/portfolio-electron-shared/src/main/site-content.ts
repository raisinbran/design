const escapeHtml = (text: string) =>
  text.replace(
    /[&<>"']/g,
    (character) =>
      ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" })[
        character
      ]!,
  );
export const jsonFile = (value: unknown) =>
  JSON.stringify(value, null, 2) + "\n";
/** Python's generated_js is a public compatibility contract; integer ratios are emitted as floats. */
export function photographyScript(catalog: PhotoCatalog): string {
  const photos = catalog.photos.map((photo) =>
    Object.fromEntries(
      Object.entries(photo).filter(
        ([key]) =>
          !["aspectRatio", "tagStatus", "altNeedsReview"].includes(key),
      ),
    ),
  );
  const ratios = catalog.photos.map((photo) => {
    const value = photo.galleryCrop
      ? (photo.aspectRatio * photo.galleryCrop.width) / photo.galleryCrop.height
      : photo.aspectRatio;
    return `  ${JSON.stringify(photo.file)}: ${Number.isInteger(value) ? value.toFixed(1) : String(value)}`;
  });
  return (
    "// GENERATED FROM data/media-catalog.json. DO NOT EDIT THIS FILE DIRECTLY.\nwindow.PORTFOLIO_PHOTOS = " +
    JSON.stringify(photos, null, 2) +
    ";\nwindow.PHOTO_ASPECT_RATIOS = " +
    (ratios.length ? "{\n" + ratios.join(",\n") + "\n}" : "{}") +
    ";\nwindow.PHOTO_TAG_LABELS = " +
    ("[" +
      catalog.photoTags.map((tag) => JSON.stringify(tag)).join(", ") +
      "]") +
    ";\n"
  );
}
function assertSafeHtml(html: string) {
  const $ = load(html, null, false);
  if ($("script,iframe,object,embed,style,link,meta,base,form").length)
    throw new Error("Rich text contains active content");
  $("*").each((_index, node) => {
    for (const [key, value] of Object.entries(
      "attribs" in node ? node.attribs : {},
    ))
      if (
        /^on/i.test(key) ||
        (["href", "src"].includes(key) &&
          /^(?:javascript|data|file):/i.test(value.trim()))
      )
        throw new Error("Rich text contains an unsafe attribute");
  });
}
export async function asset(root: string, relative: string): Promise<void> {
  let decoded: string;
  try {
    decoded = decodeURIComponent(relative);
  } catch {
    throw new Error("Invalid asset encoding");
  }
  if (
    !decoded ||
    /[\\:\x00-\x1f]/.test(decoded) ||
    decoded.startsWith("/") ||
    decoded.split("/").includes("..")
  )
    throw new Error("Use a portfolio-relative asset path");
  if (!(await stat(await workspaceFile(root, decoded))).isFile())
    throw new Error(`Missing portfolio asset: ${relative}`);
}
const percentages = (value: string) =>
  typeof value === "string" &&
  /^\d+(?:\.\d+)?% \d+(?:\.\d+)?%$/.test(value) &&
  value.split(" ").every((part) => parseFloat(part) <= 100);
const identifier = (value: string) => /^[A-Za-z][A-Za-z0-9_-]*$/.test(value);
export async function validateContent(
  root: string,
  catalogs: WorkspaceCatalogs,
  baseline: WorkspaceCatalogs,
): Promise<void> {
  const photoNames = new Set<string>();
  for (const photo of catalogs.photography.photos) {
    const folded = photo.file.toLowerCase();
    if (photoNames.has(folded))
      throw new Error("Photo names must be unique ignoring case");
    photoNames.add(folded);
    if (!photo.alt.trim()) throw new Error("Every photo needs a description");
    if (photo.tags.some((tag) => !catalogs.photography.photoTags.includes(tag)))
      throw new Error("Unknown photography tag");
    if (photo.galleryCrop) {
      const { x, y, width, height } = photo.galleryCrop;
      if (
        ![x, y, width, height].every(Number.isFinite) ||
        x < 0 ||
        y < 0 ||
        width <= 0 ||
        height <= 0 ||
        x + width > 1.000001 ||
        y + height > 1.000001
      )
        throw new Error("Invalid gallery crop");
    }
  }
  for (const project of catalogs.engineering.projects) {
    if (
      !identifier(project.id) ||
      !project.title.trim() ||
      !percentages(project.coverPosition) ||
      typeof project.visible !== "boolean" ||
      typeof project.expanded !== "boolean"
    )
      throw new Error("Invalid Engineering project settings");
    const prior = baseline.engineering.projects.find(
      (item) => item.id === project.id,
    );
    if (prior?.bodyHtml !== project.bodyHtml) assertSafeHtml(project.bodyHtml);
    if (project.legacyHtml !== prior?.legacyHtml && project.legacyHtml)
      throw new Error(
        "Engineering source templates cannot be edited through catalog fields",
      );
    for (const media of project.media)
      if (
        media.html &&
        !prior?.media.some((original) => original.html === media.html)
      )
        throw new Error(
          "Media source templates cannot be edited through catalog fields",
        );
    for (const name of [
      project.cover,
      ...project.media.map((media) => media.src),
    ])
      if (name) await asset(root, name);
    for (const media of project.media)
      if (!media.src)
        throw new Error("Every Engineering media item needs a file");
  }
  if (!catalogs.archive.collections.length)
    throw new Error("Keep at least one Archive collection");
  const archiveIds = new Set<string>();
  const archiveFiles = new Set<string>();
  for (const collection of catalogs.archive.collections) {
    if (
      !identifier(collection.id) ||
      archiveIds.has(collection.id) ||
      !collection.title.trim() ||
      !percentages(collection.coverPosition) ||
      !["cover", "contain", "auto"].includes(collection.coverSize) ||
      !/^\d+(?:\.\d+)?(?:em|rem|px)$/.test(collection.headerMinHeight) ||
      typeof collection.expanded !== "boolean"
    )
      throw new Error("Invalid Archive collection settings");
    archiveIds.add(collection.id);
    await asset(root, collection.cover);
    for (const media of collection.media) {
      if (
        !identifier(media.id) ||
        archiveIds.has(media.id) ||
        !media.alt.trim() ||
        !percentages(media.position) ||
        !["natural", "square"].includes(media.cropMode) ||
        !["low", "normal", "portraitBoost", "featured"].includes(
          media.prominence,
        ) ||
        (media.displayRatio !== null &&
          (!Number.isFinite(media.displayRatio) ||
            media.displayRatio < 0.25 ||
            media.displayRatio > 7))
      )
        throw new Error("Invalid Archive image settings");
      archiveIds.add(media.id);
      const name = path.basename(decodeURIComponent(media.src)).toLowerCase();
      if (archiveFiles.has(name))
        throw new Error("Archive image basenames must be unique");
      archiveFiles.add(name);
      await asset(root, media.src);
      for (const key of ["figureAttributes", "imageAttributes"] as const) {
        const allowed =
          key === "figureAttributes"
            ? ["class", "style", "data-display-ratio", "data-crop-mode"]
            : [
                "class",
                "style",
                "loading",
                "decoding",
                "width",
                "height",
                "title",
              ];
        for (const [name, value] of Object.entries(media[key]))
          if (
            !allowed.includes(name) ||
            !(
              typeof value === "string" ||
              (name === "class" &&
                Array.isArray(value) &&
                value.every((item) => typeof item === "string"))
            ) ||
            (name === "style" &&
              /url\s*\(|expression|javascript:/i.test(String(value)))
          )
            throw new Error("Unsafe Archive HTML attributes");
      }
    }
  }
}
function engineeringFragment(project: EngineeringProject): string {
  const keys = [
    "id",
    "title",
    "heading",
    "context",
    "bodyHtml",
    "cover",
    "coverPosition",
    "media",
    "visible",
    "expanded",
  ];
  if (
    project.legacyHtml &&
    project.baseline &&
    keys.every(
      (key) =>
        JSON.stringify(project[key]) === JSON.stringify(project.baseline![key]),
    )
  )
    return project.legacyHtml;
  const $ = load(
    project.legacyHtml ||
      '<details class="project"><summary class="project-header"><span class="project-header-bg" aria-hidden="true"></span><span class="project-header-shade" aria-hidden="true"></span><span class="project-header-text"></span><span class="project-chevron-wrap"><span class="project-chevron"></span></span></summary><div class="project-body"><h2></h2><p class="lead"></p><hr class="project-title-divider"><div class="project-prose"></div><div class="project-gallery" data-justified-gallery></div></div></details>',
    null,
    false,
  );
  const section = $("details").first().attr("id", project.id);
  if (project.expanded) section.attr("open", "");
  else section.removeAttr("open");
  section.find(".project-header-text").text(project.title);
  section.find(".project-body > h2").text(project.heading);
  if (!section.find(".project-body > .lead").length)
    section.find(".project-body > h2").after('<p class="lead"></p>');
  section.find(".project-body > .lead").text(project.context);
  section
    .find(".project-header-bg")
    .attr(
      "style",
      `background-image:url("${project.cover.replace(/["\\\n\r]/g, "")}");background-position:${project.coverPosition}`,
    );
  section.find(".project-prose").html(project.bodyHtml);
  section.find(".project-gallery").html(
    project.media
      .map((media) => {
        const m = load(
          media.html || '<figure class="project-media"></figure>',
          null,
          false,
        );
        const figure = m("figure").first();
        figure.find("figcaption").remove();
        if (media.kind === "image") {
          figure.find("video,a").remove();
          if (!figure.find("img").length)
            figure.prepend('<img loading="lazy" decoding="async">');
          figure.find("img").attr("src", media.src).attr("alt", media.alt);
        } else {
          figure.find("img,a").remove();
          if (!figure.find("video").length)
            figure.prepend('<video controls preload="metadata"></video>');
          const source = figure.find("video source");
          (source.length ? source : figure.find("video")).attr(
            "src",
            media.src,
          );
        }
        if (media.caption || media.credit)
          figure.append(
            `<figcaption>${media.caption ? `<span class="caption-main">${escapeHtml(media.caption)}</span>` : ""}${media.credit ? `<small>${escapeHtml(media.credit)}</small>` : ""}</figcaption>`,
          );
        return m.html();
      })
      .join(""),
  );
  return $.html();
}
export function engineeringPage(
  catalog: EngineeringCatalog,
  page: string,
): string {
  const start = "<!-- portfolio-studio:engineering:start -->";
  const end = "<!-- portfolio-studio:engineering:end -->";
  const content = catalog.projects
    .filter((project) => project.visible)
    .map(
      (project) => engineeringFragment(project) + (project.separator ?? "\n"),
    )
    .join("");
  if (page.includes(start) && page.includes(end))
    return (
      page.slice(0, page.indexOf(start) + start.length) +
      "\n" +
      content +
      "\n" +
      page.slice(page.indexOf(end))
    );
  const matches = [...page.matchAll(/<details\b[\s\S]*?<\/details>/gi)];
  if (!matches.length)
    throw new Error("Engineering section boundaries missing");
  const first = matches[0].index!;
  const last = matches.at(-1)!;
  const finish = last.index! + last[0].length;
  return page.slice(first, finish) === content
    ? page
    : page.slice(0, first) +
        start +
        "\n" +
        content +
        "\n" +
        end +
        page.slice(finish);
}
function archiveFragment(collection: ArchiveCollection, raw?: string): string {
  const $ = load(
    raw ||
      '<details class="project"><summary class="project-header"><span class="project-header-bg" aria-hidden="true"></span><span class="project-header-shade"></span><span class="project-header-text"></span><span class="project-chevron-wrap"><span class="project-chevron"></span></span></summary><div class="project-body"><h2></h2><hr class="project-title-divider"><div class="project-gallery" data-justified-gallery></div></div></details>',
    null,
    false,
  );
  const section = $("details").first().attr("id", collection.id);
  if (collection.expanded) section.attr("open", "");
  else section.removeAttr("open");
  section.find(".project-header-text").text(collection.title);
  section
    .find(".project-header")
    .attr("style", `min-height:${collection.headerMinHeight}`);
  section
    .find(".project-header-bg")
    .attr(
      "style",
      `background-image:url("${collection.cover.replace(/["\\\n\r]/g, "")}");background-position:${collection.coverPosition};background-size:${collection.coverSize}`,
    );
  section.find(".project-body > h2").text(collection.heading);
  section.find(".project-body > .lead").remove();
  if (collection.context)
    section
      .find(".project-body > h2")
      .after(`<p class="lead">${escapeHtml(collection.context)}</p>`);
  section.find(".project-gallery").html(
    collection.media
      .map((media) => {
        const m = load(
          '<figure class="project-media"><img loading="lazy" decoding="async"></figure>',
          null,
          false,
        );
        const figure = m("figure");
        const image = figure.find("img");
        for (const [name, value] of Object.entries(media.figureAttributes))
          figure.attr(name, Array.isArray(value) ? value.join(" ") : value);
        for (const [name, value] of Object.entries(media.imageAttributes))
          image.attr(name, Array.isArray(value) ? value.join(" ") : value);
        figure.attr("id", media.id).attr("data-crop-mode", media.cropMode);
        if (media.displayRatio !== null)
          figure.attr("data-display-ratio", String(media.displayRatio));
        image
          .attr("src", media.src)
          .attr("alt", media.alt)
          .css("object-position", media.position);
        if (media.caption || media.credit)
          figure.append(
            `<figcaption>${media.caption ? `<span class="caption-main">${escapeHtml(media.caption)}</span>` : ""}${media.credit ? `<small>${escapeHtml(media.credit)}</small>` : ""}</figcaption>`,
          );
        return m.html();
      })
      .join(""),
  );
  return $.html();
}
export function archiveOutput(
  catalog: ArchiveCatalog,
  baseline: ArchiveCatalog,
  page: string,
  settings: string,
): { page: string; settings: string; catalog: ArchiveCatalog } {
  if (
    catalog.sourceSha256 !== digest(catalog.sourceHtml) ||
    catalog.sourceHtml.replace(/\r\n/g, "\n") !== page.replace(/\r\n/g, "\n") ||
    catalog.settingsSource.replace(/\r\n/g, "\n") !==
      settings.replace(/\r\n/g, "\n")
  )
    throw new Error(
      "Archive template changed externally. Reload before saving.",
    );
  if (
    JSON.stringify(catalog.collections) === JSON.stringify(baseline.collections)
  )
    return { page, settings, catalog };
  const matches = [...page.matchAll(/<details\b[\s\S]*?<\/details>/gi)];
  if (!matches.length) throw new Error("Archive collection boundaries missing");
  const fragments = catalog.collections.map((collection) => {
    const prior = baseline.collections.find(
      (item) => item.id === collection.id,
    );
    const raw = matches.find((match) => {
      const $ = load(match[0], null, false);
      return $("details").attr("id") === collection.id;
    })?.[0];
    const htmlEqual =
      prior &&
      JSON.stringify({
        ...collection,
        media: collection.media.map(({ prominence, ...media }) => media),
      }) ===
        JSON.stringify({
          ...prior,
          media: prior.media.map(({ prominence, ...media }) => media),
        });
    return raw && htmlEqual ? raw : archiveFragment(collection, raw);
  });
  const newline = page.includes("\r\n") ? "\r\n" : "\n";
  const separators = matches
    .slice(0, -1)
    .map((match, index) =>
      page.slice(match.index! + match[0].length, matches[index + 1].index),
    );
  const last = matches.at(-1)!;
  const output =
    page.slice(0, matches[0].index) +
    fragments
      .map(
        (fragment, index) =>
          fragment +
          (index < fragments.length - 1
            ? (separators[index] ?? newline + newline)
            : ""),
      )
      .join("") +
    page.slice(last.index! + last[0].length);
  const overrides = Object.fromEntries(
    catalog.collections
      .flatMap((collection) =>
        collection.media
          .filter((media) => media.prominence !== "normal")
          .map((media) => [
            path.basename(decodeURIComponent(media.src)).toLowerCase(),
            media.prominence,
          ]),
      )
      .sort(([a], [b]) => a.localeCompare(b)),
  );
  const updatedSettings =
    JSON.stringify(overrides) === JSON.stringify(catalog.prominenceOverrides)
      ? settings
      : settings.replace(
          /(window\.ARCHIVE_PHOTO_PROMINENCE\s*=\s*Object\.freeze\()\{[\s\S]*?\}(\)\s*;)/,
          (_whole, before, after) => before + JSON.stringify(overrides) + after,
        );
  return {
    page: output,
    settings: updatedSettings,
    catalog: {
      ...catalog,
      sourceHtml: output,
      sourceSha256: digest(output),
      settingsSource: updatedSettings,
      prominenceOverrides: overrides,
    },
  };
}
